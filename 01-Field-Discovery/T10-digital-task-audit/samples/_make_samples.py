def main() -> None:
    for name, (difficulty, text) in SAMPLES.items():
        p = HERE / f"{name}.txt"
        p.write_text(text + "\n", encoding="utf-8")
        print(f"[样本] {p.name}  <- {difficulty}")

    gt = HERE / "_ground_truth.csv"
    with gt.open("w", encoding="utf-8-sig", newline="") as fh:
        w = csv.writer(fh)
        w.writerow(["file", "include_in_eval", "course", "date_iso", "time_start",
                    "time_end", "location", "deadline", "action"])
        w.writerows(GROUND_TRUTH)
    print(f"[标注] {gt.name}  共 {len(GROUND_TRUTH)} 行（其中 {sum(r[1] for r in GROUND_TRUTH)} 行纳入评估）")


if __name__ == "__main__":
    main()
