"""抽取规则表。

刻意与 extractor.py 分离：任何"日志显示某字段漏抽率上升"的迭代，
都只需要改动本文件里的词表/正则，产出的 Git diff 会非常小且可读。
"""
from __future__ import annotations

# ---------------------------------------------------------------- 日期
# 2026年11月22日 / 11月22日 / 11月22号
DATE_YMD = r"(?:(?P<y>\d{4})\s*年\s*)?(?P<m>\d{1,2})\s*月\s*(?P<d>\d{1,2})\s*[日号]"
# 本周五 / 下周三 / 周日
DATE_WEEK = r"(?:(?P<wk>本|这|下)\s*)?周(?P<w>[一二三四五六日天])"
# 今天 / 明晚 / 后天
DATE_REL = r"(?P<rel>大后天|后天|明天|明日|明晚|明早|今天|今日|今晚)"
# 11/22 或 11-22（无年份）
DATE_SLASH = r"(?<![\d/])(?P<m>\d{1,2})\s*[/\-]\s*(?P<d>\d{1,2})(?![\d/])"

# ---------------------------------------------------------------- 时间
TIME_HM = r"(?P<ap>上午|下午|中午|晚上|傍晚|早上|凌晨)?\s*(?P<h>\d{1,2})\s*[:：]\s*(?P<mi>\d{2})"
TIME_H = r"(?P<ap>上午|下午|中午|晚上|傍晚|早上|凌晨)?\s*(?P<h>\d{1,2})\s*[点时](?P<mi>半|\d{1,2})?\s*分?"

# ---------------------------------------------------------------- 截止
# 命中任一提示词，且窗口内出现日期 => 判定为 deadline
DEADLINE_CUES = (
    "截止", "截至", "请于", "务必于", "之前", "以前", "最后期限",
    "前提交", "前报名", "前完成", "前填写", "前上交", "前确认", "前缴费",
)
DEADLINE_WINDOW_BEFORE = 16
DEADLINE_WINDOW_AFTER = 12
# 无提示词的情形："明天下午3点前把作业交了" / "今晚22:00前发我" —— 时间后紧跟"前"即视为截止
DEADLINE_TIME_SUFFIX = r"(?:\d{1,2}[:：]\d{2}|\d{1,2}\s*[点时]\s*\d*)\s*(?:之前|以前|前)(?![前后])"

# 地点匹配结果开头常见的动词/介词，需剥离
PLACE_LEADING_NOISE = ("在", "于", "到", "去", "至", "从", "位于", "地点在")

# ---------------------------------------------------------------- 地点
PLACE_LABEL = r"(?:地\s*点|地\s*址|集合地点|活动地点|举办地点)\s*[:：]?\s*([^\n，。；、]{2,24})"
PLACE_ROOM = (
    r"([\u4e00-\u9fa5A-Za-z0-9]{1,12}(?:实训室|实验室|教室|机房|自习室|阅览室|报告厅|会议室|"
    r"体育馆|图书馆|活动室|办公室|工作室|广场|操场|食堂|公寓|宿舍楼|教学楼|实验楼|"
    r"中心|馆|楼|厅|场|门|站))"
)
# 地点匹配必须有「在/于/到/至/去」之类介词，或本身含数字（教室号），否则容易误抓
PLACE_PREPOSITIONS = ("在", "于", "到", "至", "去", "集合")

# ---------------------------------------------------------------- 携带
BRING = r"(?:请|需|务必|记得|要求)?\s*(?:携带|自带|带上|带好|准备好)\s*([^\n，。；]{1,30})"

# ---------------------------------------------------------------- 类别
CATEGORY_KEYWORDS: dict[str, tuple[str, ...]] = {
    "报名": ("报名", "扫码报名", "填写问卷", "接龙", "抢票"),
    "会议": ("会议", "例会", "班会", "开会", "参会", "出席"),
    "讲座": ("讲座", "报告会", "分享会", "宣讲", "论坛"),
    "考试": ("考试", "测验", "补考", "机考", "笔试", "面试"),
    "作业": ("作业", "提交", "上交", "截止交", "实验报告", "大作业", "验收", "答辩"),
    "活动": ("活动", "比赛", "竞赛", "晚会", "社团", "志愿", "招募"),
    "缴费": ("缴费", "交费", "费用", "缴纳", "收费"),
    "借还": ("借", "归还", "领取", "领取器材", "归还器材", "签收"),
}

# ---------------------------------------------------------------- 优先级
# 距截止时间的小时数阈值
PRIORITY_P0_HOURS = 24
PRIORITY_P1_HOURS = 72
PRIORITY_P2_HOURS = 24 * 7

# ---------------------------------------------------------------- 噪声
# 群聊里常见的无意义行，抽取前先剔除
NOISE_PATTERNS = (
    r"^\s*\[?图片\]?\s*$",
    r"^\s*\[?(表情|语音|视频|文件|链接)\]?\s*$",
    r"^\s*@所有人\s*$",
    r"^\s*[-=*_]{3,}\s*$",
)

# 【紧急】这类是标签不是标题，遇到就跳过方括号、改从正文取标题
TITLE_TAG_WORDS = ("紧急", "重要", "通知", "公告", "提醒", "注意", "转发", "帮转", "置顶", "必看")
